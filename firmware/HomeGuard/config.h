// 置信度阈值：低于该值的结果直接丢弃，不参与报警
#define HG_CONF_THRESHOLD    0.85f

// 需要连续多少次推理判为同一类事件才真正报警（抑制单次误判）
#define HG_CONFIRM_FRAMES    3


// =====================================================
// 音频参数
// =====================================================

#define SAMPLE_RATE          16000
#define AUDIO_BUFFER_SIZE    512        // 每次从 I2S 读取的样点数（= 一个 hop）

// I2S DMA 环形缓冲。
// CPU 在跑特征提取与 CNN 推理时，样点暂存在这里，因此
// 「单次推理耗时」必须小于该环形缓冲能覆盖的时长，见 I2S_RING_MS。
// 原始工程用的是 8 x 64（约 32ms），不足以覆盖一次 CNN 推理，故加大到 8 x 512。
#define I2S_DMA_BUF_COUNT    8
#define I2S_DMA_BUF_LEN      512
#define I2S_RING_SAMPLES     (I2S_DMA_BUF_COUNT * I2S_DMA_BUF_LEN)
#define I2S_RING_MS          ((I2S_RING_SAMPLES * 1000) / SAMPLE_RATE)


